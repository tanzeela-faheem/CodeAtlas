const MAX_FILE_SIZE_BYTES = 2 * 1024 * 1024;

export class LanguageDetectorService {
    async detectLanguages(
        repositoryPath: string
    ): Promise<LanguageDetectionResult> {
        const rootPath = path.resolve(repositoryPath);

        const rootStats = await fs.stat(rootPath);

        if (!rootStats.isDirectory()) {
            throw new Error(
                `Repository path is not a directory: ${rootPath}`
            );
        }

        const sourceFiles: SourceFile[] = [];
        const unknownExtensions = new Set<string>();

        await this.scanDirectory(
            rootPath,
            rootPath,
            false,
            sourceFiles,
            unknownExtensions
        );

        // Generated source files remain in the inventory, but are excluded
        // from developer-written language statistics.
        const countedFiles = sourceFiles.filter(
            (file) => !file.isGenerated
        );

        const linesByLanguage = new Map<ProgrammingLanguage, number>();
        const filesByLanguage = new Map<ProgrammingLanguage, number>();

        for (const file of countedFiles) {
            filesByLanguage.set(
                file.language,
                (filesByLanguage.get(file.language) ?? 0) + 1
            );

            linesByLanguage.set(
                file.language,
                (linesByLanguage.get(file.language) ?? 0) +
                    file.linesOfCode
            );
        }

        const totalSourceFiles = countedFiles.length;

        const totalLinesOfCode = countedFiles.reduce(
            (total, file) => total + file.linesOfCode,
            0
        );

        const languages: LanguageStatistics[] = [
            ...filesByLanguage.keys()
        ].map((language) => {
            const fileCount = filesByLanguage.get(language) ?? 0;
            const linesOfCode = linesByLanguage.get(language) ?? 0;

            return {
                language,
                fileCount,
                linesOfCode,
                percentageOfSourceFiles: totalSourceFiles > 0
                    ? Number(
                        ((fileCount / totalSourceFiles) * 100).toFixed(2)
                    )
                    : 0,
                percentageOfLinesOfCode: totalLinesOfCode > 0
                    ? Number(
                        ((linesOfCode / totalLinesOfCode) * 100).toFixed(2)
                    )
                    : 0
            };
        }).sort((a, b) => b.linesOfCode - a.linesOfCode);

       const dominantLanguage = languages[0]?.language ?? null;


        const result: LanguageDetectionResult = {
            languages,
            sourceFiles,
            unknownExtensions: [...unknownExtensions].sort(),
            totalSourceFiles,
            totalLinesOfCode,
            dominantLanguage,
            detectedAt: new Date().toISOString()
        };

        console.log("\n========== LANGUAGE DETECTION ==========");
        console.log(`Repository: ${rootPath}`);
        console.log(`Source files counted: ${totalSourceFiles}`);
        console.log(`Generated source files: ${
            sourceFiles.filter((file) => file.isGenerated).length
        }`);
        console.log(`Total lines of code: ${totalLinesOfCode}`);
        console.log(`Dominant language: ${dominantLanguage ?? "Unknown"}`);

        console.log("\nLanguage statistics:");
        console.table(languages);

        if (result.unknownExtensions.length > 0) {
            console.log(
                "Unrecognized source-like extensions:",
                result.unknownExtensions
            );
        }

        console.log("========================================\n");

        return result;
    }

    private async scanDirectory(
        rootPath: string,
        currentPath: string,
        inheritedGenerated: boolean,
        sourceFiles: SourceFile[],
        unknownExtensions: Set<string>
    ): Promise<void> {
        const entries = await fs.readdir(currentPath, {
            withFileTypes: true
        });

        for (const entry of entries) {
            const absolutePath = path.join(currentPath, entry.name);

            // Do not follow symbolic links outside the repository or create
            // duplicate traversal paths through linked directories.
            if (entry.isSymbolicLink()) {
                continue;
            }

            if (entry.isDirectory()) {
                if (IGNORED_DIRECTORIES.has(entry.name.toLowerCase())) {
                    continue;
                }

                const generatedDirectory =
                    GENERATED_DIRECTORY_NAMES.has(entry.name.toLowerCase());

                await this.scanDirectory(
                    rootPath,
                    absolutePath,
                    inheritedGenerated || generatedDirectory,
                    sourceFiles,
                    unknownExtensions
                );

                continue;
            }

            if (!entry.isFile()) {
                continue;
            }

            const extension = path.extname(entry.name).toLowerCase();

            const language = await this.identifyLanguage(
                absolutePath,
                extension
            );

            if (!language) {
                if (SOURCE_LIKE_EXTENSIONS.has(extension)) {
                    unknownExtensions.add(extension);
                }

                continue;
            }

            const stats = await fs.stat(absolutePath);

            // Avoid reading huge files into memory during this initial scan.
            if (stats.size > MAX_FILE_SIZE_BYTES) {
                continue;
            }

            const content = await fs.readFile(absolutePath, "utf8");

            const relativePath = path.relative(
                rootPath,
                absolutePath
            ).split(path.sep).join("/");

            const isGenerated =
                inheritedGenerated ||
                this.isGeneratedFile(entry.name, relativePath, content);

            sourceFiles.push({
                absolutePath,
                relativePath,
                extension,
                language,
                linesOfCode: this.countLinesOfCode(content, language),
                isGenerated
            });
        }
    }

    private async identifyLanguage(
        filePath: string,
        extension: string
    ): Promise<ProgrammingLanguage | null> {
        const mappedLanguage = EXTENSION_LANGUAGE[extension];

        if (!mappedLanguage) {
            return null;
        }

        // Header files may contain C or C++ declarations.
        if (extension === ".h") {
            const content = await this.readSmallSample(filePath);

            if (
                /\b(namespace|template\s*<|std::|class\s+\w+)/.test(content)
            ) {
                return "C++";
            }

            return "C";
        }

        // MATLAB scripts and Objective-C source both use the .m extension.
        if (extension === ".m") {
            const content = await this.readSmallSample(filePath);

            if (
                /@interface\b|@implementation\b|#import\s+[<"]/.test(content)
            ) {
                return "Objective-C";
            }

            if (
                /^\s*function\b/m.test(content) ||
                /^\s*end\s*$/m.test(content) ||
                /\bdisp\s*\(/.test(content)
            ) {
                return "MATLAB";
            }

            return "Objective-C";
        }

        return mappedLanguage;
    }

    private async readSmallSample(filePath: string): Promise<string> {
        const handle = await fs.open(filePath, "r");

        try {
            const buffer = Buffer.alloc(8192);
            const { bytesRead } = await handle.read(
                buffer,
                0,
                buffer.length,
                0
            );

            return buffer.toString("utf8", 0, bytesRead);
        } finally {
            await handle.close();
        }
    }

    private isGeneratedFile(
        fileName: string,
        relativePath: string,
        content: string
    ): boolean {
        const normalizedPath = relativePath.toLowerCase();
        const normalizedName = fileName.toLowerCase();

        if (
            normalizedName.endsWith(".min.js") ||
            normalizedName.endsWith(".min.css") ||
            normalizedName.endsWith(".generated.ts") ||
            normalizedName.endsWith(".generated.js") ||
            normalizedName.endsWith(".designer.cs") ||
            normalizedName.endsWith(".g.cs") ||
            normalizedName.endsWith(".pb.go") ||
            normalizedName.endsWith("_pb2.py")
        ) {
            return true;
        }

        // Recognize common generator banners without scanning the full file.
        const header = content.slice(0, 1200);

        if (
            /generated by .*do not edit/i.test(header) ||
            /auto-generated file/i.test(header) ||
            /<auto-generated/i.test(header) ||
            /code generated .* DO NOT EDIT/i.test(header)
        ) {
            return true;
        }

        return normalizedPath.split("/").some((part) =>
            GENERATED_DIRECTORY_NAMES.has(part)
        );
    }

    private countLinesOfCode(
        content: string,
        language: ProgrammingLanguage
    ): number {
        const lines = content.split(/\r?\n/);

        let count = 0;
        let insideBlockComment = false;

        const supportsSlashComments = [
            "JavaScript",
            "TypeScript",
            "Java",
            "C",
            "C++",
            "C#",
            "Go",
            "Rust",
            "Kotlin",
            "Swift",
            "Scala",
            "Dart",
            "CSS",
            "Objective-C"
        ].includes(language);

        for (const originalLine of lines) {
            const line = originalLine.trim();

            if (!line) {
                continue;
            }

            if (supportsSlashComments) {
                let remaining = line;

                if (insideBlockComment) {
                    const closeIndex = remaining.indexOf("*/");

                    if (closeIndex === -1) {
                        continue;
                    }

                    remaining = remaining.slice(closeIndex + 2).trim();
                    insideBlockComment = false;
                }

                if (!remaining) {
                    continue;
                }

                if (remaining.startsWith("/*")) {
                    const closeIndex = remaining.indexOf("*/", 2);

                    if (closeIndex === -1) {
                        insideBlockComment = true;
                        continue;
                    }

                    remaining = remaining.slice(closeIndex + 2).trim();

                    if (!remaining) {
                        continue;
                    }
                }

                if (
                    remaining.startsWith("//") ||
                    remaining.startsWith("*")
                ) {
                    continue;
                }

                count++;
                continue;
            }

            if (
                ["Python", "Ruby", "Shell", "PowerShell", "R", "Perl"].includes(
                    language
                ) &&
                line.startsWith("#")
            ) {
                continue;
            }

            if (
                ["SQL", "Lua", "Haskell", "Elixir"].includes(language) &&
                line.startsWith("--")
            ) {
                continue;
            }

            if (
                ["HTML", "CSS"].includes(language) &&
                line.startsWith("<!--")
            ) {
                continue;
            }

            count++;
        }

        return count;
    }
}
