
import * as fs from "fs";
import * as path from "path";

import type {
    DirectoryCategory,
    DirectoryInfo,
    ProjectModuleInfo,
    ProjectStructureResult,
    ProgrammingLanguage,
} from "../types/project-detection.types.js";

export class ProjectStructureAnalyzerService {
    private readonly ignoredDirectories = new Set([
        ".git",
        ".svn",
        "node_modules",
        "vendor",
        ".next",
        ".nuxt",
        "dist",
        "build",
        "coverage",
        ".cache",
        ".idea",
        ".vscode",
        "__pycache__",
        "target",
        "bin",
        "obj",
    ]);

    private readonly sourceDirectoryNames = new Set([
        "src",
        "source",
        "sources",
        "app",
        "lib",
        "pkg",
    ]);

    private readonly testDirectoryNames = new Set([
        "test",
        "tests",
        "__tests__",
        "spec",
        "specs",
    ]);

    private readonly resourceDirectoryNames = new Set([
        "resources",
        "resource",
        "assets",
        "static",
        "public",
        "templates",
    ]);

    private readonly generatedDirectoryNames = new Set([
        "generated",
        "autogenerated",
        "codegen",
    ]);

    private readonly buildOutputDirectoryNames = new Set([
        "dist",
        "build",
        "out",
        "target",
        "bin",
        "obj",
        "coverage",
    ]);

    private readonly dependencyDirectoryNames = new Set([
        "node_modules",
        "vendor",
        "packages",
    ]);

    private readonly configurationFileNames = new Set([
        "package.json",
        "tsconfig.json",
        "jsconfig.json",
        "vite.config.js",
        "vite.config.ts",
        "webpack.config.js",
        "webpack.config.ts",
        "next.config.js",
        "next.config.ts",
        "next.config.mjs",
        "next.config.ts",
        "pyproject.toml",
        "requirements.txt",
        "setup.py",
        "Cargo.toml",
        "go.mod",
        "pom.xml",
        "build.gradle",
        "build.gradle.kts",
        "settings.gradle",
        "settings.gradle.kts",
        "Makefile",
        "CMakeLists.txt",
        "Dockerfile",
        "docker-compose.yml",
        "docker-compose.yaml",
        ".gitignore",
        ".env.example",
    ]);

    private readonly documentationFileNames = new Set([
        "README",
        "CONTRIBUTING",
        "CHANGELOG",
        "LICENSE",
        "CODE_OF_CONDUCT",
    ]);

    private readonly extensionLanguageMap: Record<
        string,
        ProgrammingLanguage
    > = {
        ".ts": "TypeScript",
        ".tsx": "TypeScript",
        ".js": "JavaScript",
        ".jsx": "JavaScript",
        ".mjs": "JavaScript",
        ".cjs": "JavaScript",
        ".py": "Python",
        ".java": "Java",
        ".kt": "Kotlin",
        ".kts": "Kotlin",
        ".go": "Go",
        ".rs": "Rust",
        ".c": "C",
        ".h": "C",
        ".cpp": "C++",
        ".cc": "C++",
        ".hpp": "C++",
        ".cs": "C#",
        ".php": "PHP",
        ".rb": "Ruby",
        ".swift": "Swift",
        ".scala": "Scala",
        ".html": "HTML",
        ".css": "CSS",
        ".scss": "CSS",
        ".sql": "SQL",
        ".sh": "Shell",
        ".bat": "Shell",
        ".ps1": "Shell",
    };

    analyze(repositoryPath: string): ProjectStructureResult {
        const root = path.resolve(repositoryPath);

        if (!fs.existsSync(root)) {
            throw new Error(
                `Repository path does not exist: ${root}`,
            );
        }

        if (!fs.statSync(root).isDirectory()) {
            throw new Error(
                `Repository path is not a directory: ${root}`,
            );
        }

        const directories: DirectoryInfo[] = [];
        const sourceRoots = new Set<string>();
        const testDirectories = new Set<string>();
        const resourceDirectories = new Set<string>();
        const configurationFiles = new Set<string>();
        const documentationFiles = new Set<string>();

        const moduleLanguages = new Map<
            string,
            Map<ProgrammingLanguage, number>
        >();

        const moduleSourceDirectories = new Map<
            string,
            Set<string>
        >();

        const moduleFileCounts = new Map<string, number>();

        let totalFiles = 0;
        let totalDirectories = 0;

        const recordLanguage = (
            modulePath: string,
            filePath: string,
        ): void => {
            const extension = path.extname(filePath).toLowerCase();
            const language = this.extensionLanguageMap[extension];

            if (!language) {
                return;
            }

            if (!moduleLanguages.has(modulePath)) {
                moduleLanguages.set(modulePath, new Map());
            }

            const counts = moduleLanguages.get(modulePath)!;
            counts.set(language, (counts.get(language) ?? 0) + 1);
        };

        const walk = (
            currentPath: string,
            relativePath: string,
        ): void => {
            let entries: fs.Dirent[];

            try {
                entries = fs.readdirSync(currentPath, {
                    withFileTypes: true,
                });
            } catch {
                return;
            }

            let directFileCount = 0;

            for (const entry of entries) {
                const absolutePath = path.join(
                    currentPath,
                    entry.name,
                );

                const childRelativePath = relativePath
                    ? path.join(relativePath, entry.name)
                    : entry.name;

                if (entry.isSymbolicLink()) {
                    continue;
                }

                if (entry.isDirectory()) {
                    if (
                        this.ignoredDirectories.has(entry.name) ||
                        entry.name.startsWith(".")
                    ) {
                        continue;
                    }

                    totalDirectories++;

                    const category = this.classifyDirectory(
                        entry.name,
                        childRelativePath,
                    );

                    if (category === "source") {
                        sourceRoots.add(childRelativePath);
                    }

                    if (category === "test") {
                        testDirectories.add(childRelativePath);
                    }

                    if (category === "resource") {
                        resourceDirectories.add(childRelativePath);
                    }

                    walk(absolutePath, childRelativePath);

                    const childFileCount = this.countFilesInDirectory(
                        absolutePath,
                    );

                    directories.push({
                        path: childRelativePath,
                        category,
                        fileCount: childFileCount,
                    });

                    continue;
                }

                if (!entry.isFile()) {
                    continue;
                }

                totalFiles++;
                directFileCount++;

                const fileName = entry.name;
                const normalizedRelativePath =
                    childRelativePath.split(path.sep).join("/");

                if (this.isConfigurationFile(fileName)) {
                    configurationFiles.add(normalizedRelativePath);
                }

                if (this.isDocumentationFile(fileName)) {
                    documentationFiles.add(normalizedRelativePath);
                }

                const parentPath = relativePath || ".";
                const modulePath = this.findModulePath(
                    relativePath,
                );

                moduleFileCounts.set(
                    modulePath,
                    (moduleFileCounts.get(modulePath) ?? 0) + 1,
                );

                if (!moduleSourceDirectories.has(modulePath)) {
                    moduleSourceDirectories.set(
                        modulePath,
                        new Set(),
                    );
                }

                const sourceDirs =
                    moduleSourceDirectories.get(modulePath)!;

                if (
                    this.sourceDirectoryNames.has(
                        path.basename(parentPath).toLowerCase(),
                    )
                ) {
                    sourceDirs.add(parentPath);
                }

                recordLanguage(modulePath, absolutePath);
            }

            // Root is represented by the overall result rather than
            // an entry in the directory list.
            void directFileCount;
        };

        walk(root, "");

        const modules: ProjectModuleInfo[] = [];

        for (const [modulePath, languageCounts] of moduleLanguages) {
            const languages = Array.from(languageCounts.keys());

            modules.push({
                name:
                    modulePath === "."
                        ? path.basename(root)
                        : path.basename(modulePath),
                path: modulePath,
                languages,
                sourceDirectories: Array.from(
                    moduleSourceDirectories.get(modulePath) ?? [],
                ),
            });
        }

        // Include modules that contain files but have no recognized
        // programming-language extensions.
        for (const [modulePath] of moduleFileCounts) {
            if (modules.some((module) => module.path === modulePath)) {
                continue;
            }

            modules.push({
                name:
                    modulePath === "."
                        ? path.basename(root)
                        : path.basename(modulePath),
                path: modulePath,
                languages: [],
                sourceDirectories: Array.from(
                    moduleSourceDirectories.get(modulePath) ?? [],
                ),
            });
        }

        return {
            directories: directories.sort((a, b) =>
                a.path.localeCompare(b.path),
            ),
            sourceRoots: Array.from(sourceRoots).sort(),
            testDirectories: Array.from(testDirectories).sort(),
            resourceDirectories: Array.from(
                resourceDirectories,
            ).sort(),
            configurationFiles: Array.from(
                configurationFiles,
            ).sort(),
            documentationFiles: Array.from(
                documentationFiles,
            ).sort(),
            modules: modules.sort((a, b) =>
                a.path.localeCompare(b.path),
            ),
            totalFiles,
            totalDirectories,
            detectedAt: new Date().toISOString(),
        };
    }

    private classifyDirectory(
        directoryName: string,
        relativePath: string,
    ): DirectoryCategory {
        const name = directoryName.toLowerCase();
        const normalizedPath = relativePath.toLowerCase();

        if (this.testDirectoryNames.has(name)) {
            return "test";
        }

        if (this.generatedDirectoryNames.has(name)) {
            return "generated";
        }

        if (this.buildOutputDirectoryNames.has(name)) {
            return "build-output";
        }

        if (this.dependencyDirectoryNames.has(name)) {
            return "dependency";
        }

        if (this.sourceDirectoryNames.has(name)) {
            return "source";
        }

        if (this.resourceDirectoryNames.has(name)) {
            return "resource";
        }

        if (
            name === "config" ||
            name === "configuration" ||
            name === "configs"
        ) {
            return "configuration";
        }

        if (
            name === "docs" ||
            name === "documentation"
        ) {
            return "documentation";
        }

        if (normalizedPath.split("/").length === 1) {
            return "module";
        }

        return "other";
    }

    private isConfigurationFile(fileName: string): boolean {
        if (this.configurationFileNames.has(fileName)) {
            return true;
        }

        return (
            fileName.endsWith(".config.js") ||
            fileName.endsWith(".config.ts") ||
            fileName.endsWith(".config.mjs") ||
            fileName.endsWith(".config.cjs") ||
            fileName.endsWith(".config.json") ||
            fileName.endsWith(".yaml") ||
            fileName.endsWith(".yml") ||
            fileName.endsWith(".toml")
        );
    }

    private isDocumentationFile(fileName: string): boolean {
        const upperName = fileName.toUpperCase();

        return (
            this.documentationFileNames.has(
                path.parse(upperName).name,
            ) ||
            fileName.toLowerCase().endsWith(".md") ||
            fileName.toLowerCase().endsWith(".rst") ||
            fileName.toLowerCase().endsWith(".adoc")
        );
    }

    private findModulePath(relativePath: string): string {
    if (!relativePath) {
        return ".";
    }

    const parts = relativePath.split(path.sep);
    return parts[0] ?? ".";
}

    private countFilesInDirectory(directoryPath: string): number {
        let count = 0;

        const visit = (currentPath: string): void => {
            let entries: fs.Dirent[];

            try {
                entries = fs.readdirSync(currentPath, {
                    withFileTypes: true,
                });
            } catch {
                return;
            }

            for (const entry of entries) {
                if (entry.isSymbolicLink()) {
                    continue;
                }

                const fullPath = path.join(
                    currentPath,
                    entry.name,
                );

                if (entry.isDirectory()) {
                    if (
                        this.ignoredDirectories.has(entry.name) ||
                        entry.name.startsWith(".")
                    ) {
                        continue;
                    }

                    visit(fullPath);
                } else if (entry.isFile()) {
                    count++;
                }
            }
        };

        visit(directoryPath);
        return count;
    }
}
